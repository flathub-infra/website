def _assert_secret_hash_absent(response):
    assert response.status_code < 400, response.text
    assert "client_secret_hash" not in response.text
    assert "client_secret_hash" not in response.json()


def _create_tables(connection):
    statements = [
        """
        CREATE TEMP TABLE flathubuser (
            id integer PRIMARY KEY, display_name varchar, default_account varchar,
            deleted boolean NOT NULL DEFAULT false, banned boolean NOT NULL DEFAULT false,
            accepted_publisher_agreement_at timestamp, oidc_subject varchar UNIQUE,
            invite_code varchar UNIQUE
        ) ON COMMIT PRESERVE ROWS
        """,
        """
        CREATE TEMP TABLE permission (
            name varchar PRIMARY KEY, created_at timestamp NOT NULL DEFAULT now()
        ) ON COMMIT PRESERVE ROWS
        """,
        """
        CREATE TEMP TABLE role (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name varchar UNIQUE, created_at timestamp NOT NULL DEFAULT now()
        ) ON COMMIT PRESERVE ROWS
        """,
        """
        CREATE TEMP TABLE role_permission (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            role_id integer NOT NULL REFERENCES role(id),
            permission_name varchar NOT NULL REFERENCES permission(name)
        ) ON COMMIT PRESERVE ROWS
        """,
        """
        CREATE TEMP TABLE flathubuser_role (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            flathubuser_id integer NOT NULL REFERENCES flathubuser(id),
            role_id integer NOT NULL REFERENCES role(id)
        ) ON COMMIT PRESERVE ROWS
        """,
        """
        CREATE TEMP TABLE oidcclient (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            client_id varchar NOT NULL UNIQUE, client_secret_hash varchar NOT NULL,
            name varchar NOT NULL, description varchar, redirect_uris jsonb NOT NULL,
            allowed_scopes jsonb NOT NULL, enabled boolean NOT NULL DEFAULT true,
            refresh_tokens_enabled boolean NOT NULL DEFAULT false,
            require_pkce boolean NOT NULL DEFAULT true,
            trusted boolean NOT NULL DEFAULT false,
            created_at timestamp NOT NULL DEFAULT now(), updated_at timestamp NOT NULL DEFAULT now(),
            created_by_user_id integer REFERENCES flathubuser(id) ON DELETE SET NULL,
            secret_rotated_at timestamp
        ) ON COMMIT PRESERVE ROWS
        """,
        """
        CREATE TEMP TABLE oidcaccesstoken (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            client_id varchar NOT NULL REFERENCES oidcclient(client_id) ON DELETE CASCADE,
            user_id integer NOT NULL REFERENCES flathubuser(id) ON DELETE CASCADE,
            access_token_hash varchar NOT NULL UNIQUE, scope varchar NOT NULL,
            created_at timestamp NOT NULL DEFAULT now(), expires_at timestamp NOT NULL,
            revoked_at timestamp, refresh_token_family_id varchar, authorization_code_id integer
        ) ON COMMIT PRESERVE ROWS
        """,
        """
        CREATE TEMP TABLE oidcrefreshtoken (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            client_id varchar NOT NULL REFERENCES oidcclient(client_id) ON DELETE CASCADE,
            user_id integer NOT NULL REFERENCES flathubuser(id) ON DELETE CASCADE,
            refresh_token_hash varchar NOT NULL UNIQUE, family_id varchar NOT NULL,
            authorization_code_id integer, scope varchar NOT NULL,
            created_at timestamp NOT NULL DEFAULT now(), expires_at timestamp NOT NULL,
            rotated_at timestamp, revoked_at timestamp, replaced_by_id integer
        ) ON COMMIT PRESERVE ROWS
        """,
    ]
    for statement in statements:
        connection.execute(text(statement))
    connection.execute(
        text(
            "INSERT INTO flathubuser (id, display_name) VALUES "
            "(1, 'OIDC administrator'), (2, 'Regular user')"
        )
    )
    connection.execute(
        text("INSERT INTO permission (name) VALUES ('manage-oidc-clients')")
    )
    connection.execute(text("INSERT INTO role (id, name) VALUES (1, 'oidc-admin')"))
    connection.execute(
        text(
            "INSERT INTO role_permission (role_id, permission_name) "
            "VALUES (1, 'manage-oidc-clients')"
        )
    )
    connection.execute(
        text("INSERT INTO flathubuser_role (flathubuser_id, role_id) VALUES (1, 1)")
    )
    connection.commit()


@pytest.fixture
def admin_api():
    database_url = os.getenv("OIDC_TEST_DATABASE_URL")
    if not database_url:
        pytest.skip("OIDC_TEST_DATABASE_URL is not configured")
    engine = create_engine(database_url)
    connection = engine.connect()
    _create_tables(connection)
    Session = sessionmaker(bind=connection, expire_on_commit=False)
    current_login: dict[str, LoginState | int | None] = {
        "state": LoginState.LOGGED_OUT,
        "user_id": None,
    }

    def current_login_state():
        user_id = cast("int | None", current_login["user_id"])
        user = (
            cast("FlathubUser", SimpleNamespace(id=user_id))
            if user_id is not None
            else None
        )
        return LoginInformation(cast("LoginState", current_login["state"]), user, None)

    app = FastAPI()
    app.add_middleware(cast("Any", SessionMiddleware), secret_key="test-session-secret")
    app.dependency_overrides[login_state] = current_login_state
    oidc_admin.register_to_app(app)
    app.add_middleware(cache.CacheControlMiddleware)

    @contextmanager
    def real_db(db_type="writer"):
        session = Session()
        try:
            yield DBSession(session)
            if db_type == "writer":
                session.commit()
        finally:
            session.close()

    with (
        patch("app.routes.oidc_admin.get_db", side_effect=real_db),
        patch("app.login_info.get_db", side_effect=real_db),
        patch("app.routes.oidc_admin.audit_log.enqueue_audit_log"),
        TestClient(app, raise_server_exceptions=False) as client,
    ):
        yield client, Session, current_login
    connection.close()
    engine.dispose()


def _login_as(current_login, user_id):
    current_login["state"] = LoginState.LOGGED_IN
    current_login["user_id"] = user_id


def _stored_client(session_factory, client_id):
    session = session_factory()
    try:
        return session.query(OidcClient).filter_by(client_id=client_id).one()
    finally:
        session.close()


def test_admin_authentication_and_disabled_oidc_setting(admin_api, monkeypatch):
    client, _Session, current_login = admin_api
    monkeypatch.setattr(config.settings, "oidc_enabled", False)
    response = client.get("/admin/oidc-clients")
    assert response.status_code == 401
    assert response.headers["Cache-Control"] == "private"
    _login_as(current_login, 2)
    response = client.get("/admin/oidc-clients")
    assert response.status_code == 403
    assert response.headers["Cache-Control"] == "private"
    _login_as(current_login, 1)
    response = client.get("/admin/oidc-clients")
    assert response.status_code == 200
    assert response.headers["Cache-Control"] == "private"
    assert response.json() == []


def test_redirect_and_scope_validation(admin_api):
    client, _Session, current_login = admin_api
    _login_as(current_login, 1)
    for redirect_uri in (
        "relative/callback",
        "https://example.com/*",
        "https://example.com/callback#fragment",
        "http://example.com/callback",
    ):
        response = client.post(
            "/admin/oidc-clients",
            json={**VALID_CLIENT, "redirect_uris": [redirect_uri]},
        )
        assert response.status_code == 422
        assert response.headers["Cache-Control"] == "no-store"
    for payload in (
        {**VALID_CLIENT, "allowed_scopes": ["profile"]},
        {**VALID_CLIENT, "allowed_scopes": ["openid", "offline_access"]},
    ):
        response = client.post("/admin/oidc-clients", json=payload)
        assert response.status_code == 422
        assert response.headers["Cache-Control"] == "no-store"
    response = client.post(
        "/admin/oidc-clients",
        json={**VALID_CLIENT, "redirect_uris": ["HTTP://LOCALHOST:8000/callback"]},
    )
    assert response.status_code == 201
    assert response.headers["Cache-Control"] == "no-store"
    assert response.headers["Pragma"] == "no-cache"
    assert response.json()["redirect_uris"] == ["http://localhost:8000/callback"]
    _assert_secret_hash_absent(response)


def test_create_list_get_patch_rotate_and_secret_invalidation(admin_api):
    client, Session, current_login = admin_api
    _login_as(current_login, 1)
    response = client.post("/admin/oidc-clients", json=VALID_CLIENT)
    assert response.status_code == 201
    assert response.headers["Cache-Control"] == "no-store"
    assert response.headers["Pragma"] == "no-cache"
    created = response.json()
    first_secret, client_id = created["client_secret"], created["client_id"]
    assert verify_client_secret(
        first_secret, _stored_client(Session, client_id).client_secret_hash
    )

    for response in (
        client.get("/admin/oidc-clients"),
        client.get(f"/admin/oidc-clients/{client_id}"),
        client.patch(
            f"/admin/oidc-clients/{client_id}",
            json={"name": "Updated client", "description": "Updated", "trusted": True},
        ),
    ):
        _assert_secret_hash_absent(response)
    assert (
        client.get(f"/admin/oidc-clients/{client_id}").json()["name"]
        == "Updated client"
    )
    assert client.get(f"/admin/oidc-clients/{client_id}").json()["trusted"] is True
    assert _stored_client(Session, client_id).trusted is True

    old_hash = _stored_client(Session, client_id).client_secret_hash
    response = client.post(f"/admin/oidc-clients/{client_id}/rotate-secret")
    assert response.status_code == 200
    assert response.headers["Cache-Control"] == "no-store"
    assert response.headers["Pragma"] == "no-cache"
    rotated_secret = response.json()["client_secret"]
    stored = _stored_client(Session, client_id)
    assert stored.client_secret_hash != old_hash
    assert verify_client_secret(rotated_secret, stored.client_secret_hash)
    assert not verify_client_secret(first_secret, stored.client_secret_hash)


def test_disable_revokes_active_tokens_and_disables_client(admin_api):
    client, Session, current_login = admin_api
    _login_as(current_login, 1)
    response = client.post(
        "/admin/oidc-clients",
        json={
            **VALID_CLIENT,
            "name": "Token client",
            "refresh_tokens_enabled": True,
            "allowed_scopes": ["openid", "offline_access"],
        },
    )
    assert response.status_code == 201
    _assert_secret_hash_absent(response)
    client_id = response.json()["client_id"]
    now = utcnow()
    session = Session()
    try:
        session.add(
            OidcAccessToken(
                client_id=client_id,
                user_id=1,
                access_token_hash=hash_token("active-access"),
                scope="openid",
                created_at=now,
                expires_at=now + timedelta(hours=1),
            )
        )
        session.add(
            OidcRefreshToken(
                client_id=client_id,
                user_id=1,
                refresh_token_hash=hash_token("active-refresh"),
                family_id="family-1",
                scope="openid offline_access",
                created_at=now,
                expires_at=now + timedelta(hours=1),
            )
        )
        session.commit()
    finally:
        session.close()

    response = client.delete(f"/admin/oidc-clients/{client_id}")
    assert response.status_code == 200
    _assert_secret_hash_absent(response)
    assert response.json()["enabled"] is False
    assert response.json()["active_token_count"] == 0
    session = Session()
    try:
        access, refresh = (
            session.query(OidcAccessToken).one(),
            session.query(OidcRefreshToken).one(),
        )
        stored = session.query(OidcClient).filter_by(client_id=client_id).one()
        assert access.revoked_at is not None
        assert refresh.revoked_at is not None
        assert oidc_client_enabled(stored) is False
    finally:
        session.close()
