"""Generate report models from the pinned checker artifact schemas.

Upstream: https://github.com/flathub-infra/flatpak-external-data-checker
Revision: 3531052185551c5040ba06272ee129db091b90f3
Run: python schemas/checker-health/generate.py (from backend/).
"""

import json
import subprocess
from pathlib import Path
from tempfile import TemporaryDirectory

directory = Path(__file__).resolve().parent
backend = directory.parents[1]
report = json.loads((directory / "report.v1.schema.json").read_text())
# Name provenance variants by source rather than their position in the union.
checker = report["$defs"]["checker"]
variants = checker.pop("oneOf")
checker_refs = []
for variant in variants:
    name = f"{variant['properties']['source']['const']}_checker"
    report["$defs"][name] = {
        **checker,
        "properties": {
            key: value | variant["properties"].get(key, {})
            for key, value in checker["properties"].items()
        },
    }
    checker_refs.append({"$ref": f"#/$defs/{name}"})
report["$defs"]["checker"] = {"oneOf": checker_refs}
state = json.loads((directory / "source-state.v1.schema.json").read_text())
definitions = state.pop("$defs")
report["$defs"].update(definitions["source-state"])
report["$defs"]["timestamp"] = definitions["timestamp"]
state.pop("$id")
state.pop("$schema")
report["$defs"]["source_state"] = state
bundled = (
    json.dumps(report)
    .replace("#/$defs/source-state/", "#/$defs/")
    .replace('"source-state.v1.schema.json"', '"#/$defs/source_state"')
)

with TemporaryDirectory() as temporary:
    schema = Path(temporary) / "report.v1.schema.json"
    schema.write_text(bundled)
    subprocess.run(
        [
            "uvx",
            "--from",
            "datamodel-code-generator==0.91.0",
            "datamodel-codegen",
            "--input",
            str(schema),
            "--input-file-type",
            "jsonschema",
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--target-python-version",
            "3.13",
            "--enum-field-as-literal",
            "all",
            "--collapse-root-models",
            "--extra-fields",
            "ignore",
            "--field-constraints",
            "--strict-refs",
            "--formatters",
            "black",
            "isort",
            "--class-name",
            "CheckerReport",
            "--disable-timestamp",
            "--custom-file-header",
            "# Generated by schemas/checker-health/generate.py. Do not edit.",
            "--output",
            str(backend / "app/checker_report.py"),
        ],
        check=True,
    )
subprocess.run(
    ["uv", "run", "ruff", "check", "--fix", "app/checker_report.py"],
    cwd=backend,
    check=True,
)
subprocess.run(
    ["uv", "run", "ruff", "format", "app/checker_report.py"], cwd=backend, check=True
)
